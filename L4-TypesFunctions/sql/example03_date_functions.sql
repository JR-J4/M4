-- ============================================================
-- 7. Різниця між датами: DATEDIFF
-- ============================================================
-- Сценарій: скільки днів минуло від 1 січня до 12 лютого?

SELECT
    DATEDIFF('1997-02-12', '1997-01-01') AS days_passed,
    DATEDIFF('1997-01-01', '1997-02-12') AS reversed;
-- | days_passed | reversed |
-- |          42 |      -42 |
