/*
 * Лекція 4. SQL-типи даних та SQL-функції
 * Тема: функції для роботи з датою і часом
 *
 *   CURDATE(), CURTIME(), NOW()          сьогодні / зараз
 *   YEAR(d), MONTH(d), DAY(d)            частини дати
 *   HOUR(t), MINUTE(t), SECOND(t)        частини часу
 *   DAYNAME(d), MONTHNAME(d)             назва дня тижня / місяця
 *   DATE_ADD(d, INTERVAL 30 DAY)         додати до дати
 *   DATE_SUB(d, INTERVAL 1 MONTH)        відняти від дати
 *   DATEDIFF(d1, d2)                     різниця d1 - d2 у днях
 *   d BETWEEN 'з' AND 'по'               дата в діапазоні
 *
 * Аналогія: календар на стіні — подивитися день тижня, відрахувати
 * 30 днів уперед, порахувати, скільки днів до відпустки.
 *
 * Де застосовують: звіти за місяць, «за останні 30 днів», дедлайни, вік.
 *
 * Дані w3schools — за 1996–1997 роки. Тому там, де потрібне «сьогодні»,
 * беремо останню дату в базі — '1997-02-12'. У реальному проєкті на її місці CURDATE().
 */


-- ============================================================
-- 1. Сьогодні і зараз
-- ============================================================
-- Результат залежить від моменту запуску, тому в коментарі його немає.

SELECT
    CURDATE() AS today,
    CURTIME() AS time_now,
    NOW()     AS date_and_time;


-- ============================================================
-- 2. Розбираємо дату на частини
-- ============================================================
-- Сценарій: з дати замовлення дістаємо рік, місяць, день і день тижня.

SELECT
    YEAR('1997.02.12')      AS year,
    MONTH('1997-02-12')     AS month,
    DAY('1997-02-12')       AS day,
    DAYNAME('1997.02.12')   AS day_name,
    MONTHNAME('1997-02-12') AS month_name;
-- | year | month | day | day_name  | month_name |
-- | 1997 |     2 |  12 | Wednesday | February   |


-- ============================================================
-- 3. Замовлення по місяцях
-- ============================================================
-- Сценарій: керівник хоче бачити, скільки замовлень було кожного місяця.

SELECT
    YEAR(OrderDate)      AS year,
    MONTHNAME(OrderDate) AS month,
    COUNT(*)             AS orders
FROM Orders
GROUP BY YEAR(OrderDate), MONTH(OrderDate), MONTHNAME(OrderDate)
ORDER BY YEAR(OrderDate), MONTH(OrderDate);
-- | year | month     | orders |
-- | 1996 | July      |     22 |
-- | 1996 | August    |     25 |
-- | 1996 | September |     23 |
-- | 1996 | October   |     26 |
-- | 1996 | November  |     25 |
-- | 1996 | December  |     31 |
-- | 1997 | January   |     33 |
-- | 1997 | February  |     11 |


-- ============================================================
-- 4. Події за період: BETWEEN
-- ============================================================
-- Сценарій: скільки замовлень було у грудні 1996?

SELECT COUNT(*) AS december_orders
FROM Orders
WHERE OrderDate BETWEEN '1996-12-01' AND '1996-12-31';
-- 31


-- ============================================================
-- 5. Додаємо і віднімаємо дні
-- ============================================================
-- Сценарій: доставка — протягом 14 днів від замовлення. До якої дати привезти?

SELECT
    OrderID,
    OrderDate,
    DATE_ADD(OrderDate, INTERVAL 14 DAY) AS deliver_by
FROM Orders
ORDER BY OrderDate DESC, OrderID DESC
LIMIT 3;
-- | OrderID | OrderDate  | deliver_by |
-- |   10443 | 1997-02-12 | 1997-02-26 |
-- |   10442 | 1997-02-11 | 1997-02-25 |
-- |   10441 | 1997-02-10 | 1997-02-24 |


-- ============================================================
-- 6. Замовлення за останні 30 днів
-- ============================================================
-- Сценарій: звіт «за останні 30 днів» — межа рахується від сьогодні, а не вписана руками.

SELECT COUNT(*) AS last_30_days
FROM Orders
WHERE OrderDate BETWEEN DATE_SUB('1997-02-12', INTERVAL 30 DAY) AND '1997-02-12';
-- 32

